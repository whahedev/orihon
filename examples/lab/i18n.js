export function labT(locale, key, vars = {}) {
  const table = labMessages[locale] || labMessages.en;
  let text = table[key] ?? labMessages.en[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function applyLabDomI18n(locale) {
  const lang = labMessages[locale] ? locale : DEFAULT_LAB_LOCALE;
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll("[data-i18n]")) {
    el.textContent = labT(lang, el.getAttribute("data-i18n"));
  }
  for (const el of document.querySelectorAll("[data-i18n-placeholder]")) {
    el.setAttribute("placeholder", labT(lang, el.getAttribute("data-i18n-placeholder")));
  }
  for (const el of document.querySelectorAll("[data-i18n-title]")) {
    el.setAttribute("title", labT(lang, el.getAttribute("data-i18n-title")));
  }
  for (const el of document.querySelectorAll("[data-i18n-aria]")) {
    el.setAttribute("aria-label", labT(lang, el.getAttribute("data-i18n-aria")));
  }
  for (const el of document.querySelectorAll("[data-i18n-value]")) {
    el.value = labT(lang, el.getAttribute("data-i18n-value"));
  }
  return lang;
}
